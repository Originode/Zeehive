#!/usr/bin/env node
// GENERATE THE MIGRATION THAT PUTS THE COMMITTED ENTRY-POINT DOC BACK INTO project_doc.body.
//
// Why this exists: `project_doc.body` generates AGENTS.md and every other provider file, but house
// rule 11 stops generation from writing over a COMMITTED CLAUDE.md — so the two are copies of one
// document with nothing keeping them equal. test/project-doc-drift.test.mjs goes red when they
// diverge (ticket #38); this is the cheap way to make it green again, and the only supported one:
// editing the row instead is an edit to the copy nobody reviews, which is what caused #38.
//
// It is a SNAPSHOT mechanism and that is a known cost, not a surprise — the next CLAUDE.md edit
// re-opens the gap. Whether the sync should be an ACTION (`POST /projects/:id/docs/sync-from-repo`)
// instead of a migration is the recommendation in docs/entry-point-doc-source.md, which is a human's
// call. Until that is decided, this keeps the remedy to one command.
//
//   node scripts/sync-project-doc.mjs <NNN>        # get NNN from `zee migration-number`
//
// Writes db/migrations/<NNN>_project_doc_sync_claude_md.sql and prints what it embedded. It never
// touches a database: applying it is `npm run db:migrate`, like any other migration.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const num = (process.argv[2] || '').trim();
if (!/^\d{3}$/.test(num)) {
  console.error('usage: node scripts/sync-project-doc.mjs <NNN>   (a free 3-digit number — ask `zee migration-number`)');
  process.exit(2);
}
const out = resolve(repo, 'db', 'migrations', `${num}_project_doc_sync_claude_md.sql`);
if (existsSync(out)) { console.error(`${out} already exists — pick another number`); process.exit(2); }

const body = readFileSync(resolve(repo, 'CLAUDE.md'), 'utf8').replace(/\s+$/, '') + '\n';
if (body.includes('$doc$')) { console.error('CLAUDE.md contains the dollar-quote tag $doc$ — change the tag in this script'); process.exit(1); }

writeFileSync(out, `-- RE-SYNC project_doc.body FROM THE COMMITTED CLAUDE.md — generated by scripts/sync-project-doc.mjs.
--
-- The row and the committed file are two copies of ONE document (house rule 11 keeps generation off a
-- tracked path, and nothing then reconciles them). test/project-doc-drift.test.mjs fails when they
-- diverge; this closes it in the direction that is reviewable — the committed file wins, because it is
-- the copy that gets diffed, landed and blamed. An edit made only to the row is an edit to the wrong
-- copy: that is ticket #38, where eighteen tools read a containment claim this repo had disproved.
--
-- Idempotent (it sets a known text). A database with no project_doc row is a no-op, correctly: with no
-- row, lib/project-docs.js generates nothing, so there is no second copy to diverge.
-- Snapshot, by nature — see docs/entry-point-doc-source.md for the standing fix and its open decision.
UPDATE project_doc
   SET body = $doc$${body}$doc$,
       updated_at = now()
 WHERE project_id = (SELECT id FROM project WHERE lower(name) = 'zeehive' ORDER BY created_at LIMIT 1)
   AND cardinality(targets) > 0;
`);
console.log(`wrote db/migrations/${num}_project_doc_sync_claude_md.sql`);
console.log(`  embedded CLAUDE.md: ${body.length} chars, ${body.split('\n').length - 1} lines`);
console.log('  apply with: npm run db:migrate   ·  verify with: node test/project-doc-drift.test.mjs');
